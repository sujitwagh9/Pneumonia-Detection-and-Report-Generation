"""Written report generation (Gemini) and PDF export."""
import logging
import os
from datetime import datetime

import markdown
import matplotlib
from fpdf import FPDF
from fpdf.fonts import TextStyle
from markupsafe import escape
from PIL import Image

log = logging.getLogger(__name__)

GEMINI_MODEL = os.environ.get('GEMINI_MODEL', 'gemini-3.5-flash')
GEMINI_TIMEOUT_MS = 60_000
FONT_DIR = os.path.join(matplotlib.get_data_path(), 'fonts', 'ttf')
DISCLAIMER = ("Generated by an experimental AI model. This is not a medical diagnosis and must be "
              "reviewed by a qualified radiologist or physician.")

SYSTEM_INSTRUCTION = """You draft preliminary chest X-ray screening notes for a radiologist to review.
Rules:
- Use ONLY the model outputs you are given. Do not invent patient details (name, age, sex, history,
  symptoms, vitals) or radiological findings that are not stated.
- Grad-CAM shows where the classifier focused, not confirmed pathology. Say so when you mention it.
- Be explicit about uncertainty, especially when the probability is close to the decision threshold.
- Write in Markdown with these sections: "## Summary", "## Model findings",
  "## Interpretation and limitations", "## Suggested next steps".
- Keep it under 350 words. No signature, no placeholders like [Patient Name], no title line."""


def _client():
    # GEMINI_API_KEY is documented; API_KEY is accepted for older .env files
    api_key = os.environ.get('GEMINI_API_KEY') or os.environ.get('API_KEY')
    if not api_key:
        return None
    from google import genai
    from google.genai import types
    return genai.Client(api_key=api_key, http_options=types.HttpOptions(timeout=GEMINI_TIMEOUT_MS))


def build_prompt(result):
    finding = 'Pneumonia detected' if result['is_pneumonia'] else 'No pneumonia detected'
    region = result.get('attention_region') or 'no distinct focus'
    return (
        "Chest X-ray screened by an EfficientNetB0 binary classifier (NORMAL vs PNEUMONIA).\n"
        f"- Model finding: {finding}\n"
        f"- Pneumonia probability: {result['probability']:.3f} (decision threshold {result['threshold']})\n"
        f"- Confidence in the finding: {result['confidence']:.1%}\n"
        f"- Grad-CAM attention concentrated in: {region}\n"
        "Draft the screening note."
    )


def generate_report(result):
    """Return the Markdown report, or None if Gemini is not configured or the call fails."""
    client = _client()
    if client is None:
        log.warning("GEMINI_API_KEY is not set; skipping the written report")
        return None
    from google.genai import types
    try:
        response = client.models.generate_content(
            model=GEMINI_MODEL,
            contents=build_prompt(result),
            config=types.GenerateContentConfig(system_instruction=SYSTEM_INSTRUCTION, temperature=0.2),
        )
        return response.text or None
    except Exception:
        log.exception("Gemini report generation failed")
        return None


def markdown_to_html(text):
    # Escape first so HTML in model output is shown as text, never rendered
    return markdown.markdown(str(escape(text)))


class ReportPDF(FPDF):
    def __init__(self):
        super().__init__()
        self.add_font('DejaVu', '', os.path.join(FONT_DIR, 'DejaVuSans.ttf'))
        self.add_font('DejaVu', 'B', os.path.join(FONT_DIR, 'DejaVuSans-Bold.ttf'))
        self.add_font('DejaVu', 'I', os.path.join(FONT_DIR, 'DejaVuSans-Oblique.ttf'))
        self.add_font('DejaVu', 'BI', os.path.join(FONT_DIR, 'DejaVuSans-BoldOblique.ttf'))
        self.set_auto_page_break(auto=True, margin=20)

    def footer(self):
        self.set_y(-15)
        self.set_font('DejaVu', 'I', 7.5)
        self.set_text_color(110, 120, 135)
        self.multi_cell(0, 3.5, f"{DISCLAIMER}  ·  Page {self.page_no()}", align='C')


def _aspect_ratio(path):
    with Image.open(path) as img:
        return img.height / img.width


def build_pdf(result, report_text, original_path, gradcam_path, out_path):
    pdf = ReportPDF()
    pdf.add_page()

    pdf.set_font('DejaVu', 'B', 18)
    pdf.set_text_color(15, 27, 45)
    pdf.cell(0, 10, 'Chest X-Ray Analysis Report', new_x='LMARGIN', new_y='NEXT')
    pdf.set_font('DejaVu', '', 9)
    pdf.set_text_color(91, 107, 130)
    pdf.cell(0, 6, f"Generated {datetime.now():%d %b %Y, %H:%M}", new_x='LMARGIN', new_y='NEXT')
    pdf.ln(4)

    finding = 'Pneumonia detected' if result['is_pneumonia'] else 'No pneumonia detected'
    pdf.set_font('DejaVu', 'B', 14)
    pdf.set_text_color(*((210, 59, 59) if result['is_pneumonia'] else (18, 134, 90)))
    pdf.cell(0, 9, finding, new_x='LMARGIN', new_y='NEXT')

    pdf.set_text_color(15, 27, 45)
    rows = [
        ('Confidence in finding', f"{result['confidence']:.1%}"),
        ('Pneumonia probability', f"{result['probability']:.3f} (threshold {result['threshold']})"),
        ('Model attention (Grad-CAM)', result.get('attention_region') or 'No distinct focus'),
    ]
    for label, value in rows:
        pdf.set_font('DejaVu', 'B', 10)
        pdf.cell(62, 7, label)
        pdf.set_font('DejaVu', '', 10)
        pdf.cell(0, 7, value, new_x='LMARGIN', new_y='NEXT')
    pdf.ln(4)

    # Original and Grad-CAM side by side
    aspect = _aspect_ratio(original_path)
    width = (pdf.epw - 6) / 2
    height = width * aspect
    if height > 110:
        height = 110
        width = height / aspect
    if pdf.get_y() + height + 8 > pdf.page_break_trigger:
        pdf.add_page()
    top = pdf.get_y()
    pdf.set_font('DejaVu', '', 9)
    pdf.set_text_color(91, 107, 130)
    pdf.cell(width + 6, 5, 'Original')
    pdf.cell(width, 5, 'Grad-CAM overlay', new_x='LMARGIN', new_y='NEXT')
    pdf.image(original_path, x=pdf.l_margin, y=top + 6, w=width, h=height)
    pdf.image(gradcam_path, x=pdf.l_margin + width + 6, y=top + 6, w=width, h=height)
    pdf.set_y(top + height + 12)

    pdf.set_text_color(15, 27, 45)
    pdf.set_font('DejaVu', 'B', 13)
    pdf.cell(0, 8, 'Detailed report', new_x='LMARGIN', new_y='NEXT')
    pdf.set_font('DejaVu', '', 10)
    if report_text:
        heading = TextStyle(font_family='DejaVu', font_style='B', font_size_pt=11.5,
                            color=(15, 27, 45), t_margin=5, b_margin=2)
        pdf.write_html(markdown_to_html(report_text), font_family='DejaVu', li_prefix_color=(15, 27, 45),
                       tag_styles={'h1': heading, 'h2': heading, 'h3': heading})
    else:
        pdf.set_text_color(154, 98, 0)
        pdf.multi_cell(0, 6, "The written report could not be generated. The classification and "
                             "Grad-CAM visualisation above are still valid.")

    pdf.output(out_path)
    return out_path
